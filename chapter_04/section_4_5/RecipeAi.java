package chapter_04.section_4_5;

/*
 * カレーを作る手順を順番に画面へ表示するプログラムです。
 */
public class RecipeAi {
    public static void main(String[] args) {
        // カレーを作る4つの手順を表示します。
        System.out.println("野菜を切る");
        System.out.println("肉と野菜を炒める"); // 肉と野菜を一緒に炒めます。
        System.out.println("水を入れて煮込む");
        System.out.println("ルウを溶かす");
    }
}
