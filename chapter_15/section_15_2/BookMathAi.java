package chapter_15.section_15_2;

public class BookMathAi {
    // 2冊のページ数を受け取り、合計を返すメソッドです。
    public static int addPages(int firstPages, int secondPages) {
        return firstPages + secondPages;
    }

    // 1つ目の整数を2つ目の整数で割り、その商を返すメソッドです。
    public static int dividePages(int first, int second) {
        return first / second;
    }
}
